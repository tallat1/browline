import AppKit
import Observation

/// Pano geçmişi: kopyalanan metin, bağlantı, dosya ve görseller (son 50, sabitlenenler hariç).
/// Yalnız bellekte; uygulama kapanınca silinir. Parola yöneticilerinin "gizli" ve "geçici" işaretli
/// kopyaları hiç alınmaz (nspasteboard.org kuralı). Pano 0,75 sn'de bir yalnız `changeCount` ile
/// yoklanır (içerik okunmaz); içerik yalnız değişince bir kez okunur.
@MainActor
@Observable
public final class ClipboardHistory {
    public struct Item: Identifiable, Equatable, Sendable {
        public enum Content: Equatable, Sendable {
            case text(String)
            case url(URL)
            case files([URL])
            /// Özgün veri ve türü (ör. public.png, public.tiff); geri kopyalarken aynen yazılır.
            case image(Data, type: String)
        }

        public let id: UUID
        public var content: Content
        public var sourceBundleIdentifier: String?
        public var copiedAt: Date
        public var isPinned = false

        /// Satırda gösterilecek kısa metin.
        public var preview: String {
            switch content {
            case let .text(text):
                text.trimmingCharacters(in: .whitespacesAndNewlines)
                    .split(whereSeparator: \.isNewline).prefix(2).joined(separator: " ⏎ ")
            case let .url(url): url.absoluteString
            case let .files(urls):
                urls.count == 1 ? urls[0].lastPathComponent
                    : String(localized: "\(urls[0].lastPathComponent) ve \(urls.count - 1) dosya daha")
            case .image: String(localized: "Görsel")
            }
        }
    }

    public private(set) var items: [Item] = []
    /// Okumayı sistem engelliyorsa (Gizlilik › Diğer uygulamalardan yapıştırma) arayüz bunu söyler.
    public private(set) var isReadingBlocked = false

    public static let maximumItems = 50
    public static let maximumImageBytes = 8 * 1024 * 1024
    static let pollInterval: Duration = .milliseconds(750)
    /// nspasteboard.org: bu türleri taşıyan kopyalar geçmişe alınmaz (parolalar, geçici içerik).
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
    ]

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var pollTask: Task<Void, Never>?

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        lastChangeCount = pasteboard.changeCount
    }

    public var isRunning: Bool { pollTask != nil }

    public func start() {
        guard pollTask == nil else { return }
        // Açılmadan önceki pano içeriği geçmişe alınmaz; yalnız bundan sonraki kopyalar.
        lastChangeCount = pasteboard.changeCount
        if #available(macOS 15.4, *) {
            isReadingBlocked = pasteboard.accessBehavior == .alwaysDeny
            Log.integrations.notice("Pano geçmişi açık (erişim: \(String(describing: self.pasteboard.accessBehavior), privacy: .public))")
        }
        pollTask = Task { @MainActor [weak self] in
            while !Task.isCancelled {
                self?.check()
                try? await Task.sleep(for: Self.pollInterval)
            }
        }
    }

    public func stop() {
        pollTask?.cancel()
        pollTask = nil
        items.removeAll()
    }

    /// Pano değiştiyse bir kez okur (testler doğrudan çağırır).
    func check(source: String? = NSWorkspace.shared.frontmostApplication?.bundleIdentifier) {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredTypes),
              let content = Self.content(from: pasteboard) else { return }
        insert(content, source: source)
    }

    /// Öncelik: dosya → metin/bağlantı → görsel (Finder dosya kopyasında simge görseli de gelir).
    static func content(from pasteboard: NSPasteboard) -> Item.Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { return nil }
            if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
               let scheme = url.scheme?.lowercased(), ["http", "https"].contains(scheme), url.host != nil {
                return .url(url)
            }
            return .text(string)
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), data.count <= maximumImageBytes {
                return .image(data, type: type.rawValue)
            }
        }
        return nil
    }

    func insert(_ content: Item.Content, source: String?, now: Date = .now) {
        var pinned = false
        if let index = items.firstIndex(where: { $0.content == content }) {
            pinned = items[index].isPinned
            items.remove(at: index)
        }
        items.insert(Item(id: UUID(), content: content, sourceBundleIdentifier: source, copiedAt: now, isPinned: pinned), at: 0)
        // Sınır sabitlenmemişlere uygulanır; sabitlenenler kalır.
        var unpinnedSeen = 0
        items = items.filter { item in
            guard !item.isPinned else { return true }
            unpinnedSeen += 1
            return unpinnedSeen <= Self.maximumItems
        }
    }

    /// Öğeyi yeniden panoya koyar (kullanıcı ardından ⌘V ile yapıştırır). Kendi yazmamız geçmişe
    /// yeni öğe olarak düşmez; öğe en üste çıkar.
    public func copy(_ id: UUID) {
        guard let item = items.first(where: { $0.id == id }) else { return }
        pasteboard.clearContents()
        switch item.content {
        case let .text(text): pasteboard.setString(text, forType: .string)
        case let .url(url):
            pasteboard.setString(url.absoluteString, forType: .string)
            pasteboard.setString(url.absoluteString, forType: .URL)
        case let .files(urls): pasteboard.writeObjects(urls as [NSURL])
        case let .image(data, type): pasteboard.setData(data, forType: NSPasteboard.PasteboardType(type))
        }
        lastChangeCount = pasteboard.changeCount
        insert(item.content, source: item.sourceBundleIdentifier)
        Log.integrations.notice("Pano geçmişinden kopyalandı")
    }

    public func togglePin(_ id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
    }

    public func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
    }

    /// Sabitlenmemişleri siler.
    public func clear() {
        items.removeAll { !$0.isPinned }
    }
}
